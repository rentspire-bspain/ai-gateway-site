#!/usr/bin/env python3
"""Build supabase/functions/gateway-chat/corpus.json from the Spain Terminal repo docs plus the
latest nightly anomaly snapshot. Each chunk keeps its real source (repo path + line range + commit)
so the gateway can cite only what it actually retrieved.
usage: build_corpus.py <path-to-spain-terminal-shell checkout>"""
import json, re, subprocess, sys, os
repo = sys.argv[1]
DOCS = ["AGENTS.md","DB_GAP_REPORT.md","docs/SCORING_DATA_COVERAGE.md","docs/FLEET.md","docs/ANOMALY_DRIFT.md",
 "docs/SCORING_BAND_RECALIBRATION.md","docs/SPINE_COVERAGE_DOCTRINE.md","docs/FRESHNESS_SLA.md","docs/CRONS.md",
 "docs/SCORING_REFRESH_PIPELINE.md","docs/SCORING_INPUTS_OPTIONS.md","docs/V50_GRADE_MAPPING_VERIFICATION.md",
 "docs/v50-coverage-measurement-2026-10-23.md","docs/TERMINAL_FRESHNESS_AUDIT.md","docs/LAUNCH_READINESS.md","docs/MASTER_TERMINAL_TRACKER.md"]
SECRET = re.compile(r"eyJ[A-Za-z0-9_-]{20,}|sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{12,}|postgres(ql)?://\S+:\S+@")
commit = subprocess.check_output(["git","-C",repo,"rev-parse","--short","HEAD"]).decode().strip()
chunks = []
def add(src, start, end, text):
    text = text.strip()
    if len(text) < 60 or SECRET.search(text): return
    chunks.append({"id": len(chunks), "src": src, "lines": f"{start}-{end}", "text": text})
for rel in DOCS:
    lines = open(os.path.join(repo, rel), encoding="utf-8").read().split("\n")
    buf, start, head = [], 1, ""
    def flush(end):
        global buf, start
        if buf: add(f"{rel}@{commit}", start, end, (f"[{head}]\n" if head else "") + "\n".join(buf))
        buf = []
    for i, ln in enumerate(lines, 1):
        if ln.startswith("#"):
            flush(i - 1); start = i; head = ln.lstrip("# ").strip()
        buf.append(ln)
        if sum(len(x) + 1 for x in buf) > 1400:
            flush(i); start = i + 1
    flush(len(lines))
# live-ish snapshot from the nightly anomaly job
snap = json.loads(subprocess.check_output(["git","-C",repo,"show","origin/anomaly-data:series.jsonl"]).decode().strip().split("\n")[-1])
r = snap["rows"]; n = snap["nulls"]["public.properties_base"]; d = snap["dists"]
txt = (f"Nightly anomaly snapshot taken {snap['ts']} (properties_base is the Terminal's property spine). Row counts: properties_base {r['parcels']:,}; clean (dq_status null) {r['parcels_dq_clean']:,}; flagged {r['parcels_dq_flagged']:,} "
 f"({100*r['parcels_dq_flagged']/r['parcels']:.1f}%); tracts {r['tracts']:,}; counties {r['counties']:,}; PHA register {r['pha_register']:,}; permits {r['permits']:,}. "
 f"Null rates on properties_base (percent): " + ", ".join(f"{k} {v:.1f}" for k, v in n.items()) + ". "
 "rent_signal_source mix (percent): " + ", ".join(f"{k} {v:.1f}" for k, v in d["rent_signal_source"].items()) + ". "
 "asset_class mix (percent): " + ", ".join(f"{k} {v:.1f}" for k, v in d["properties_base_asset_class"].items()) + ".")
add(f"anomaly-data:series.jsonl (latest line, {snap['ts'][:10]}) in spain-terminal-shell", 1, 1, txt)
# gateway self-description (kept in sync with call-model defaults by hand)
gw = open(os.path.join(os.path.dirname(__file__), "GATEWAY_FACTS.md")).read()
add("ai-gateway-site/retrieval/GATEWAY_FACTS.md", 1, gw.count("\n") + 1, gw)
out = os.path.join(os.path.dirname(__file__), "..", "supabase/functions/gateway-chat/corpus.ts")
open(out, "w").write("// GENERATED by retrieval/build_corpus.py - do not edit\nexport default " + json.dumps({"built_from": commit, "chunks": chunks}, ensure_ascii=False) + ";\n")
print(len(chunks), "chunks from", commit)
